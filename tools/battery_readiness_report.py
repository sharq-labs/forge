def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(REPO / "docs" / "flagships" / "BATTERY_CONFIRMATORY_READINESS.md"))
    a = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        rec = bb.readiness(bb.dry_run(tmp))
    pathlib.Path(a.out).write_text(render(rec))
    print(rec["BATTERY_READINESS"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
