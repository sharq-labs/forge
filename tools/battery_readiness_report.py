        f"MULTIPLICITY_BUDGET: {json.dumps(mb, sort_keys=True)} (digest16 {mbd})",
        f"BLINDFOLD / ESCROW ROUTE: {r['BLINDFOLD_ESCROW_ROUTE']}",
        f"KIRKALDY_2024: {r['KIRKALDY_2024']}",
