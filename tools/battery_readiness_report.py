from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path[:0] = [str(REPO / "src"), str(REPO / "flagships")]

from forge_flagships import battery_blind as bb


