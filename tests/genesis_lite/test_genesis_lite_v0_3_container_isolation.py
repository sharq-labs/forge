def test_runtime_launch_failure_is_detected_before_consuming_the_root(monkeypatch, tmp_path):
    """Unlike the old test with an injected ['no unshare'] list, use the real
    deployment checker, with successful tool discovery but failed process launch.
    Empty plan + synthetic runner ensure this test cannot generate formal worlds.
    """
    monkeypatch.setattr(isolation, "available", lambda: True)
    monkeypatch.setattr(isolation, "kept_paths", lambda: ("/home/forge/source", "/home/forge/venv"))
    monkeypatch.setattr(isolation.shutil, "which", lambda tool: f"/usr/bin/{tool}")

    def launch_denied(*args, **kwargs):
        raise PermissionError("synthetic runtime denial after successful tool discovery")

    monkeypatch.setattr(isolation.subprocess, "run", launch_denied)
    monkeypatch.setattr(isolation.subprocess, "Popen", launch_denied)
    # Bypass unrelated identity gates only; preserve real deployment and admission.
    monkeypatch.setattr(formal, "preflight", lambda *args: [])
    monkeypatch.setattr(formal, "committed_identity_problems", lambda *args: [])
    monkeypatch.setattr(formal, "candidate_of", lambda doc: None)
    monkeypatch.setattr(formal, "registered_arms", lambda: [])
    monkeypatch.setattr(formal, "plan", lambda: [])
    monkeypatch.setattr(formal, "harness_runner", lambda doc: lambda *a, **kw: {})
    doc = {"formal": {"budget": {"total_hours": 1}}}
    registry = AttemptRegistry(tmp_path / "operator-registry")
    published, refusal = [], None
    try:
        formal.run_formal(
            bytes(range(32)), doc, manifest={}, registry=registry,
            publish=published.append, sink=lambda row: None,
        )
    except formal.FormalRefused as exc:
        refusal = str(exc)
    assert registry.entries() == [], "failed isolation consumed the one allowed root attempt"
    assert published == []
    assert refusal is not None, "runtime failure did not block pre-admission"


def _probe_in_fresh_interpreter(temp_directory: pathlib.Path, marker: pathlib.Path | None = None) -> dict:
    # Every invocation is a new process. Only tempfile location is controlled.
    # PYTHONPATH is not assumed; import THIS checkout explicitly.
    root = pathlib.Path(__file__).resolve().parents[2]
    code = (
        "import sys,tempfile,json,pathlib,hashlib;"
        "sys.path[:0]=[sys.argv[1],sys.argv[1]+'/src'];"
        "tempfile.tempdir=sys.argv[2];"
        "from benchmarks.genesis_lite.v0_3.deployment_attacks import cross_card_state;"
        "answer=cross_card_state({'universe_id':'synthetic-card'},None);"
        "answer['visible_canary_sha256']=hashlib.sha256(pathlib.Path(sys.argv[3]).read_bytes()).hexdigest() "
        "if len(sys.argv)>3 else None;"
        "print(json.dumps(answer))"
    )
    result = subprocess.run(
        [sys.executable, "-I", "-c", code, str(root), str(temp_directory)]
        + ([str(marker)] if marker is not None else []),
        check=True, capture_output=True, text=True, timeout=30,
    )
    return json.loads(result.stdout)


def test_shared_probe_directory_positive_control_survives_process_restart(tmp_path):
    """Power: a shared directory IS reached by the next card and after a restart. The first card finds nothing, and
    that is UNTESTABLE, never REFUSED: one directory is no evidence about every writable mount (the next test, N-1)."""
    temporary = tmp_path / "private-tmp"
    temporary.mkdir()
    first = _probe_in_fresh_interpreter(temporary)
    second = _probe_in_fresh_interpreter(temporary)
    restarted = _probe_in_fresh_interpreter(temporary)
    assert first["rationale"].startswith("cross_card_state:UNTESTABLE:")
    assert second["rationale"].startswith("cross_card_state:REACHED:")
    assert restarted["rationale"].startswith("cross_card_state:REACHED:")


def test_private_tmp_is_not_evidence_that_other_writable_mounts_are_private(tmp_path):
    """Model N-1 with two private TMP parents and a separately shared writable
    directory. A cryptographic canary is readable by B and after restart; the
    production probe must not issue REFUSED based solely on its TMP parent.
    This is a filesystem counterexample, not a real Podman mount experiment.
    """
    shared = tmp_path / "shared-writable-mount"
    shared.mkdir()
    canary = secrets.token_bytes(32)
    marker = shared / "canary"
    marker.write_bytes(canary)
    observed = []
    for card in ("a", "b", "b-restart"):
        temporary = tmp_path / card / "tmp"
        temporary.mkdir(parents=True)
        response = _probe_in_fresh_interpreter(temporary, marker)
        observed.append(response["rationale"])
        assert response["visible_canary_sha256"] == hashlib.sha256(canary).hexdigest()
    assert all(not rationale.startswith("cross_card_state:REFUSED:") for rationale in observed), (
        "probe certified REFUSED from private TMP while a shared writable canary "
        f"remained readable across cards and restart: {observed}"
    )
