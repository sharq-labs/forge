@pytest.mark.parametrize("target", ["/tmp", "/var/tmp", "/run", "/dev/shm"])
def test_each_required_writable_mount_is_explicit_private_tmpfs(launcher, target):
    argv = launcher.argv(["python", "-I", "host.py"], "/tmp/card-a")
    specifications = [
        argv[i + 1] for i, value in enumerate(argv[:-1]) if value == "--tmpfs"
    ] + [value.partition("=")[2] for value in argv if value.startswith("--tmpfs=")]
    assert any(value.split(":", 1)[0] == target for value in specifications), (
        f"{target} has no explicit per-container tmpfs declaration"
    )


