"""Part 16: the Core Freeze V1 manifest verifies, and its verifier can fail.

The first test is the one that matters day to day: the checked-out tree IS
Core Freeze V1, or a descendant that kept its contract. Everything after it is
about the verifier rather than the tree -- each takes the real stored manifest,
breaks exactly one fact in a copy, and requires the verifier to fail on the
check that owns that fact. A verifier that passed every one of these copies
would be a verifier that compares nothing.

The tampered copies are held in memory. Nothing here writes to the manifest.
"""

from __future__ import annotations

import copy
import json
import pathlib
import subprocess
import sys

import pytest

REPO = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = REPO / "certification" / "core_freeze_v1.json"

pytestmark = pytest.mark.skipif(
    not (REPO / ".git").exists(), reason="the freeze verifier reads git state"
)

from tools.certification import core_freeze, core_freeze_v3  # noqa: E402


@pytest.fixture(scope="module")
def live():
    return core_freeze.collect_live(REPO)


@pytest.fixture(scope="module")
def manifest():
    assert MANIFEST.exists(), "certification/core_freeze_v1.json is missing"
    return json.loads(MANIFEST.read_bytes())


def failing(result) -> set[str]:
    return set(result.failed())


# =====================================================================
# the tree
# =====================================================================

#: The V1 checks Core Freeze V4 supersedes, each with the reason, and NOTHING else may fail.
#:
#: AMENDED at Core Freeze V4 (I-29, R-65). `contract.api` compares the LIVE frozen digest with the
#: one V1 recorded, and the 2026-09-16 scientific core re-audit moved it additively (`c80e6418` ->
#: `f18aa806`, the same 194 symbols). `contract.serialization` compares the live serialization facts
#: with V1's, and this round bumped eight record schemas CONDITIONALLY -- a record that carries a new
#: binding declares a new version and an old record keeps its bytes -- so V1's recorded
#: `accepted_versions` lists are now prefixes of the live ones. Both are superseded by V4, which
#: proves the supersession additive difference by difference against the bytes V1 committed; neither
#: is softened here, they are NAMED, and the assertion below requires V4's proof to hold.
SUPERSEDED_BY_V4 = {
    "contract.api": "the frozen digest moved additively; core_freeze_v4.additive_only_problems is empty",
    "contract.serialization": "eight conditional schema bumps; every V1 version is still accepted",
    "bytes.pinned_contract_files": (
        "the two API snapshot files are re-pinned by V4. V1's pin is still checkable and is still "
        "checked: core_freeze_v4.stored_v1_frozen_snapshot reads the file OUT OF GIT at the V1 "
        "baseline commit and refuses it unless its bytes hash to the digest V1's own manifest "
        "recorded -- which is where the additive comparison starts"),
    "certificate.verifies": "the certificate is regenerated by the certificate-only child",
}


def test_the_tree_is_core_freeze_v1(live):
    """Deliberately not softened on a dirty tree, like the certificate's test."""
    result = core_freeze.verify(REPO, live=live)
    unexpected = failing(result) - set(SUPERSEDED_BY_V4)
    assert not unexpected, "\n" + result.render()
    if failing(result):
        # A superseded check may only fail while V4 PROVES the supersession. Without this the three
        # names above would be an allow-list, which is the shape this whole round exists to remove.
        from tools.certification import core_freeze_v4

        stored = core_freeze_v4.stored_v1_frozen_snapshot(REPO)
        from engcore import api_snapshot

        assert core_freeze_v4.additive_only_problems(
            stored["snapshot"], api_snapshot.frozen_only()) == []
        assert api_snapshot.frozen_only()["symbol_count"] == 194
        assert stored["file_sha256"] == json.loads(MANIFEST.read_bytes())["api"]["pinned_files"][
            core_freeze_v4.V1_FROZEN_SNAPSHOT_FILE]


def test_the_tree_is_the_exact_freeze_or_a_contract_keeping_descendant(live, manifest):
    result = core_freeze.verify_manifest(manifest, live, require_clean=False)
    assert result.mode in ("EXACT_FREEZE", "DESCENDANT"), result.mode


def test_the_command_line_verifier_agrees_with_the_function(live):
    """`python -m tools.certification.core_freeze --verify` is the Part 16 command."""
    proc = subprocess.run(
        [sys.executable, "-X", "utf8", "-m", "tools.certification.core_freeze",
         "--verify"],
        cwd=REPO, capture_output=True, text=True, encoding="utf-8",
    )
    expected = core_freeze.verify(REPO, live=live).ok
    assert (proc.returncode == 0) == expected, proc.stdout[-2000:] + proc.stderr[-2000:]
    assert proc.stdout.strip().splitlines()[-1] == ("OK" if expected else "FAILED")


