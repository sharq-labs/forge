def test_a_descendant_that_keeps_the_contract_still_verifies(live, manifest):
    """The post-freeze policy made executable: `src/` may change, the contract may not.

    Simulated by changing the RECORDED src tree hash, which is what the verifier
    sees when a later commit refactors internals. The byte-level checks must
    become informational, and the contract checks must still bind and pass.

    This is also a certificate-child self-check. The same trusted check requires
    the full verifier of the binding freeze to pass against the freshly generated
    certificate. That was Core Freeze V2; since the main audit (2026-09-15) V2's
    serialization contract is superseded and Core Freeze V3 binds, so V3 cannot
    evade the certificate-child lifecycle either.
    """
    later = copy.deepcopy(manifest)
    later["trees"]["src"] = "0" * 40
    later["domain"]["digest"] = "0" * 64  # new domain work is allowed after a freeze
    result = core_freeze.verify_manifest(later, live, require_clean=False)
    assert result.mode == "DESCENDANT"
    # AMENDED at Core Freeze V4, as the first test in this file was and for the same reason: the
    # three checks V4 supersedes fail here too, because this copy tampers with the src tree hash
    # and not with the API or the serialization facts. Nothing else may fail, and the supersession
    # must be proved, which the first test does over the same tree.
    assert set(result.failed()) <= set(SUPERSEDED_BY_V4), "\n" + result.render()
    informational = {c.name for c in result.checks if not c.binding}
    assert {"domain.digest", "bytes.reproduction_sha256"} <= informational

    # AMENDED at Core Freeze V4 (I-29, R-65): V3 is the freeze this one descends FROM, and its own
    # identity references are refused by this tree exactly as V2's were by V3 -- which is the
    # supersession, measured. So the binding freeze the certificate child may not evade is V4, and
    # V4's verifier is the one required to pass here. V3's manifest stays byte-identical and is
    # recorded in V4's by digest.
    from tools.certification import core_freeze_v4

    v4_result = core_freeze_v4.verify(REPO, require_assurance=False)
    unexpected = {c.name for c in v4_result.checks if c.binding and not c.ok} - {
        "v1.freeze_verifies", "certificate.verifies", "certificate.covers_required_areas"}
    assert not unexpected, "\nCore Freeze V4:\n" + v4_result.render()
    assert core_freeze_v4.v3_fixtures_refused()["refused"], (
        "V3's identity references are accepted, so nothing supersedes V3 and this tree is a V3 tree")


def test_on_the_exact_freeze_the_domain_digest_binds(live, manifest):
    broken = copy.deepcopy(manifest)
    broken["domain"]["digest"] = "0" * 64
    result = core_freeze.verify_manifest(broken, live, require_clean=False)
    if result.mode != "EXACT_FREEZE":
        pytest.skip("this tree is a descendant; the domain digest is informational")
    assert "domain.digest" in failing(result)


def test_a_descendant_that_breaks_the_contract_fails(live, manifest):
    later = copy.deepcopy(manifest)
    later["trees"]["src"] = "0" * 40
    later["api"]["frozen_digest"] = "0" * 64
    result = core_freeze.verify_manifest(later, live, require_clean=False)
    assert result.mode == "DESCENDANT"
    assert "contract.api" in failing(result)


