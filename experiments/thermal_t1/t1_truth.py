"""T1 hidden truth — GRADER ONLY.

**No decision-path module may import this**, enforced by an AST test.

WHY THE TRUTH IS THE ANALYTIC SOLUTION, NOT A FINE SOLVE
---------------------------------------------------------
Reality here is the exact solution of the PDE at the true diffusivity, plus
declared Gaussian noise. It is not "the solver at a very fine rung".

That distinction is the experiment. If observations were generated by a fine
solve, the reference rung would be measured against its own discretization and
would look perfect by construction, while the coarse rung's error would be
measured against a *different* numerical answer rather than against the truth.
Every rung is compared to the same exact solution, so "discretization error"
means the same thing for all three.

The truth is synthetic and known. This experiment makes no physical claim and
involves no measurement of anything real; alpha_true is chosen so the bias can
be measured against a number that is known exactly.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any

import numpy as np

from src.engcore.domains.thermal.conduction1d import exact_midpoint

from .t1_config import (
    END_TIME_S,
    LENGTH_M,
    NOISE_SEED,
    OBSERVATION_COUNT,
    OBSERVATION_SIGMA,
)

#: The diffusivity reality holds. Inside the declared prior support, and
#: deliberately off the grid spacing so no grid point sits exactly on it.
ALPHA_TRUE = 1.2e-5


def true_qoi() -> float:
    """The exact u(L/2, t_end) at the true diffusivity. No discretization."""
    return exact_midpoint(
        length_m=LENGTH_M, alpha_m2_s=ALPHA_TRUE, time_s=END_TIME_S
    )


def sensitivity() -> float:
    """du/dalpha at the true value, from the closed form.

    u = exp(-alpha pi^2 t / L^2)  ->  du/dalpha = -u pi^2 t / L^2
    Used to translate a discretization error in u into the alpha bias it
    implies, which is what makes the prediction checkable.
    """
    return -true_qoi() * np.pi**2 * END_TIME_S / LENGTH_M**2


def observations() -> tuple[float, ...]:
    """The measured values. Deterministic, and identical for every rung.

    Generated once and reused across all three inferences: if each rung saw a
    different noise draw, a difference between posteriors could be noise rather
    than discretization, and the experiment would answer nothing.
    """
    rng = np.random.default_rng(NOISE_SEED)
    centre = true_qoi()
    return tuple(
        float(centre + rng.normal(0.0, OBSERVATION_SIGMA))
        for _ in range(OBSERVATION_COUNT)
    )


def truth_payload() -> dict[str, Any]:
    return {
        "alpha_true": ALPHA_TRUE,
        "true_qoi": true_qoi(),
        "sensitivity_du_dalpha": sensitivity(),
        "observations": list(observations()),
        "truth_source": "exact analytic solution + declared Gaussian noise",
        "scope": (
            "synthetic hidden truth with a known alpha; no physical validation "
            "and no real measurement is involved"
        ),
    }


def truth_hash() -> str:
    blob = json.dumps(truth_payload(), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()
