"""The validation corpus: what evidence exists, and what it is allowed to prove.

This package is the production home of the trust vocabulary. It answers, for a
scientific claim:

* what evidence exists, and from which immutable source snapshot;
* which of it was calibration, which was independent validation, and which was
  locked holdout;
* where the model was tested, where it is supported, and where it extrapolates;
* what failed, where the failures cluster, and whether a refusal was correct;
* whether the disagreement indicts the fit, the form, the applicability or
  nothing at all.

It is offline and domain-independent by construction: it holds ids, units,
digests and arithmetic, and never learns what ``temperature`` means.
"""

