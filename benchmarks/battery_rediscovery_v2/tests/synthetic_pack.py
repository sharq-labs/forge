"""A small synthetic pack in the v2 schema, for exercising the candidate side before any real run (no real data).

``S1`` mirrors Q1's form (fitted-OCV family, UNKNOWN noise, three units, two load levels, discharge then rest);
``S2`` mirrors Q2's form (measured OCV, declared Type-B noise, rest-pulse-rest windows, no cross-unit set).  The data
are generated by the 1RC model with an OCV curve the families do not contain exactly, plus noise.
"""

from __future__ import annotations

import math
import pathlib

import numpy as np

from ..build_pack import QUESTIONS, _traj, _variables
from ..candidate.common import FITTED_OCV_BOUNDS_V, FITTED_OCV_KNOTS_SOC, MANIFEST_SCHEMA, SPEC_SCHEMA, write_json
from ..candidate.families import EQUATIONS, ocv_parameter_names


def _ocv(z):
    return 3.3 + 0.8 * np.asarray(z) - 0.3 * np.exp(-np.asarray(z) / 0.06)


def _simulate(t, i, z0, q, r0, r1, c1, rng, sigma):
    z = z0 - np.concatenate([[0.0], np.cumsum(i[1:] * np.diff(t))]) / q
    v1 = [0.0]
    for k in range(1, len(t)):
        a = math.exp(-(t[k] - t[k - 1]) / (r1 * c1))
        v1.append(a * v1[-1] + r1 * (1 - a) * i[k])
    return _ocv(z) - i * r0 - np.array(v1) + rng.normal(0.0, sigma, len(t))


def _discharge(rng, tid, unit, level, q, r0, temp0):
    n = 90
    t = np.cumsum(np.r_[0.0, 20.0 + rng.normal(0, 0.5, n - 1)])
    t_end = q * 0.92 / level
    i = np.where((t > 0) & (t < t_end), level, 0.0) + rng.normal(0, 0.002, n)
    i[0] = 0.0
    v = _simulate(t, i, 1.0, q, r0, 0.02, 1500.0, rng, 0.003)
    temp = temp0 + 3.0 * (i > 0.5) + rng.normal(0, 0.1, n)
    return _traj(tid, unit, "cc_discharge_then_rest", t, i, level, v, temp, 1.0, q)


def s1(seed: int = 0) -> dict:
    rng = np.random.default_rng(seed)
    q = 1.8 * 3600 / 4.0           # a small cell so a run stays short
    sets = {"calibration": [], "within": [], "cross": []}
    for part, units, r0 in (("calibration", "AB", 0.08), ("within", "AB", 0.085), ("cross", "C", 0.09)):
        k = 0
        for u in units:
            for level in (1.0, 2.0):
                k += 1
                sets[part].append(_discharge(rng, f"S1-{part[0]}{k:02d}", u, level, q, r0, 45.0))
    names = ocv_parameter_names(len(FITTED_OCV_KNOTS_SOC))
    bar = {"rmse_max": 0.050, "p95_abs_max": 0.090}
    return {
        "schema": SPEC_SCHEMA, "problem_id": "S1", "description": "synthetic", "clock": "t_s", "observable": "voltage_V",
        "variables": _variables("synthetic level", names, FITTED_OCV_KNOTS_SOC),
        "declared_family": {"family_id": "rc1_fitted_ocv/1", "rival": "rint_fitted_ocv/1", "equations": EQUATIONS,
                            "parameter_bounds": {"R0": [0.0001, 1.0], "R1": [1e-05, 1.0], "C1": [1.0, 1000000.0],
                                                 **{n: list(FITTED_OCV_BOUNDS_V) for n in names}},
                            "constants": {"ocv_knots_soc": list(FITTED_OCV_KNOTS_SOC)},
                            "ocv": {"status": "UNKNOWN_FITTED_TABLE", "representation": "synthetic",
                                    "knots_soc": list(FITTED_OCV_KNOTS_SOC), "bounds_V": list(FITTED_OCV_BOUNDS_V)}},
        "requested_parameters": ["R0", "R1", "C1"],
        "measurement_noise": {"sigma": None, "independent": None, "status": "UNKNOWN", "basis": "synthetic"},
        "adequacy_bar": dict(bar),
        "acceptance": {"within_unit_heldout/later_cycles": dict(bar), "cross_unit_heldout/other_cell": dict(bar)},
        "applicability": {"variables": ["level_A", "soc", "temperature_C"],
                          "widen": {"level_A": 0.05, "soc": 0.02, "temperature_C": 1.0}, "basis": "synthetic",
                          "soc_support": [0.0, 1.0]},
        "conventions": {"current_sign": "positive is discharge", "hold": "backward", "rest_band_A": 0.01,
                        "initial_state": "synthetic", "initial_polarization": "synthetic", "capacity_basis": "synthetic",
                        "scored_samples": "every sample after the first"},
        "questions": QUESTIONS,
        "sets": {"calibration": sets["calibration"], "within_unit_heldout": {"later_cycles": sets["within"]},
                 "cross_unit_heldout": {"other_cell": sets["cross"]}},
    }


def s2(seed: int = 0) -> dict:
    rng = np.random.default_rng(100 + seed)
    q = 3.0 * 3600
    knots = [[float(z), float(_ocv(z))] for z in np.linspace(0.05, 1.0, 12)]
    parts = {"calibration": [], "within": []}
    for r, z0 in enumerate((0.95, 0.85, 0.75, 0.65, 0.55, 0.45, 0.35)):
        part = "calibration" if r % 2 == 0 or r == 6 else "within"
        for level in (3.0, 6.0, 12.0):
            t = np.round(np.arange(0, 60.0, 0.1), 3)
            i = np.where((t >= 10.0) & (t < 20.0), level, 0.0)
            v = _simulate(t, i, z0, q, 0.021, 0.015, 1700.0, rng, 0.002)
            temp = 25.0 + rng.normal(0, 0.05, len(t))
            parts[part].append(_traj(f"S2-{part[0]}{len(parts[part]) + 1:02d}", "A", "rest_pulse_rest", t, i, level, v,
                                     temp, z0, q))
    bar = {"rmse_max": 0.015, "p95_abs_max": 0.030}
    return {
        "schema": SPEC_SCHEMA, "problem_id": "S2", "description": "synthetic", "clock": "t_s", "observable": "voltage_V",
        "variables": _variables("synthetic level"),
        "declared_family": {"family_id": "rc1_measured_ocv/1", "rival": "rint_measured_ocv/1", "equations": EQUATIONS,
                            "parameter_bounds": {"R0": [0.001, 0.2], "R1": [0.0001, 0.2], "C1": [1.0, 1000000.0]},
                            "constants": {"ocv_knots": knots},
                            "ocv": {"status": "MEASURED_FIXED", "interpolation": "linear", "knots_z_V": knots}},
        "requested_parameters": ["R0", "R1", "C1"],
        "measurement_noise": {"sigma": 0.005 / 3 ** 0.5, "independent": None, "status": "DECLARED_TYPE_B",
                              "half_width": 0.005, "distribution": "uniform", "basis": "synthetic"},
        "adequacy_bar": dict(bar),
        "acceptance": {"within_unit_heldout/pulses_alternate_soc": dict(bar)},
        "applicability": {"variables": ["level_A", "soc", "temperature_C"],
                          "widen": {"level_A": 0.075, "soc": 0.02, "temperature_C": 1.0}, "basis": "synthetic",
                          "soc_support": [knots[0][0], knots[-1][0]]},
        "conventions": {"current_sign": "positive is discharge", "hold": "backward", "rest_band_A": 0.075,
                        "initial_state": "synthetic", "initial_polarization": "synthetic", "capacity_basis": "synthetic",
                        "scored_samples": "every sample after the first"},
        "questions": QUESTIONS,
        "sets": {"calibration": parts["calibration"], "within_unit_heldout": {"pulses_alternate_soc": parts["within"]}},
    }


def write_pack(directory: pathlib.Path, seed: int = 0) -> pathlib.Path:
    manifest = {"schema": MANIFEST_SCHEMA, "problems": {}}
    for spec in (s1(seed), s2(seed)):
        sha = write_json(directory / f"{spec['problem_id']}.json", spec)
        manifest["problems"][spec["problem_id"]] = {"file": f"{spec['problem_id']}.json", "sha256": sha}
    write_json(directory / "MANIFEST.json", manifest)
    return directory


__all__ = ["s1", "s2", "write_pack"]
