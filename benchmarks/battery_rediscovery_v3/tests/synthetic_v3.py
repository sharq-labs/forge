"""Synthetic v3-shaped problems for dry runs (no real data).  ``S3`` mirrors the GITT kind: measured OCV from the
calibration rests only, UNKNOWN noise, rest-pulse-rest windows of two units, a within-unit and a cross-unit set.  The
data are generated by the 1RC model with an OCV curve the knots interpolate only approximately, plus noise.  ``S1`` and
``S2`` are v2's synthetic problems (fitted OCV; declared Type-B noise)."""

from __future__ import annotations

import math
import pathlib

import numpy as np

from benchmarks.battery_rediscovery_v2.build_pack import QUESTIONS, _traj, _variables
from benchmarks.battery_rediscovery_v2.candidate.common import MANIFEST_SCHEMA, SPEC_SCHEMA, write_json
from benchmarks.battery_rediscovery_v2.candidate.families import EQUATIONS
from benchmarks.battery_rediscovery_v2.tests import synthetic_pack as v2syn


def _ocv(z):
    z = np.asarray(z)
    return 3.2 + 0.85 * z - 0.25 * np.exp(-z / 0.05) + 0.01 * np.sin(12 * z)


def _ocv_linear(z):
    return 3.3 + 0.8 * np.asarray(z)


def simulate(t, i, z0, q, r0, r1, c1, rng, sigma, ocv=_ocv):
    z = z0 - np.concatenate([[0.0], np.cumsum(i[1:] * np.diff(t))]) / q
    v1, out = 0.0, [0.0]
    for k in range(1, len(t)):
        a = math.exp(-(t[k] - t[k - 1]) / (r1 * c1))
        v1 = a * v1 + r1 * (1 - a) * i[k]
        out.append(v1)
    return ocv(z) - i * r0 - np.array(out) + (rng.normal(0.0, sigma, len(t)) if sigma else 0.0)


def _window(t_pulse=60.0, level=2.5):
    t = np.concatenate([np.arange(0, 60.0, 10.0), 60.0 + np.arange(0.1, t_pulse + 1e-9, 1.0),
                        60.0 + t_pulse + np.arange(1.0, 600.0, 10.0)])
    i = np.where((t > 60.0) & (t <= 60.0 + t_pulse + 1e-9), level, 0.0)
    return t, i


def s3(seed: int = 0, r0=(0.020, 0.022), r1=0.012, c1=2500.0, sigma=0.0005, linear_ocv: bool = False) -> dict:
    """``linear_ocv``: an OCV the knots represent exactly (for parameter-recovery tests)."""
    rng = np.random.default_rng(300 + seed)
    ocv = _ocv_linear if linear_ocv else _ocv
    q = 5.0 * 3600
    z_points = [0.95 - 0.05 * k for k in range(14)]
    parts = {"calibration": [], "within": [], "cross": []}
    knots = []
    for r, z0 in enumerate(z_points):
        part = "calibration" if r % 2 == 0 or r == len(z_points) - 1 else "within"
        t, i = _window()
        v = simulate(t, i, z0, q, r0[0], r1, c1, rng, sigma, ocv)
        temp = 25.0 + rng.normal(0, 0.05, len(t))
        parts[part].append(_traj(f"S3-{part[0]}{len(parts[part]) + 1:02d}", "u1", "rest_pulse_rest", t, i, 2.5, v, temp,
                                 z0, q))
        if part == "calibration":
            knots.append([z0, float(ocv(z0))])
        if part == "within":
            v = simulate(t, i, z0, q, r0[1], r1, c1, rng, sigma, ocv)
            parts["cross"].append(_traj(f"S3-x{len(parts['cross']) + 1:02d}", "u2", "rest_pulse_rest", t, i, 2.5, v,
                                        temp, z0, q))
    knots.append([0.0, float(ocv(0.0))])
    knots = sorted(knots)
    bar = {"rmse_max": 0.015, "p95_abs_max": 0.030}
    return {
        "schema": SPEC_SCHEMA, "problem_id": "S3", "description": "synthetic", "clock": "t_s", "observable": "voltage_V",
        "variables": _variables("synthetic level"),
        "declared_family": {"family_id": "rc1_measured_ocv/1", "rival": "rint_measured_ocv/1", "equations": EQUATIONS,
                            "parameter_bounds": {"R0": [0.001, 0.2], "R1": [0.0001, 0.2], "C1": [1.0, 1000000.0]},
                            "constants": {"ocv_knots": knots},
                            "ocv": {"status": "MEASURED_FIXED", "interpolation": "linear", "knots_z_V": knots}},
        "requested_parameters": ["R0", "R1", "C1"],
        "measurement_noise": {"sigma": None, "independent": None, "status": "UNKNOWN", "basis": "synthetic"},
        "adequacy_bar": dict(bar),
        "acceptance": {"within_unit_heldout/pulses_alternate_soc": dict(bar),
                       "cross_unit_heldout/partner_cell_pulses": dict(bar)},
        "applicability": {"variables": ["level_A", "soc", "temperature_C"],
                          "widen": {"level_A": 0.05, "soc": 0.02, "temperature_C": 1.0}, "basis": "synthetic",
                          "soc_support": [knots[0][0], knots[-1][0]]},
        "conventions": {"current_sign": "positive is discharge", "hold": "backward", "rest_band_A": 0.01,
                        "initial_state": "synthetic", "initial_polarization": "synthetic", "capacity_basis": "synthetic",
                        "scored_samples": "every sample after the first"},
        "questions": QUESTIONS,
        "sets": {"calibration": parts["calibration"], "within_unit_heldout": {"pulses_alternate_soc": parts["within"]},
                 "cross_unit_heldout": {"partner_cell_pulses": parts["cross"]}},
    }


def write_pack(directory: pathlib.Path, seed: int = 0, with_s1: bool = True) -> pathlib.Path:
    manifest = {"schema": MANIFEST_SCHEMA, "problems": {}}
    specs = ([v2syn.s1(seed)] if with_s1 else []) + [v2syn.s2(seed), s3(seed)]
    for spec in specs:
        sha = write_json(directory / f"{spec['problem_id']}.json", spec)
        manifest["problems"][spec["problem_id"]] = {"file": f"{spec['problem_id']}.json", "sha256": sha}
    write_json(directory / "MANIFEST.json", manifest)
    return directory


__all__ = ["s3", "simulate", "write_pack"]
